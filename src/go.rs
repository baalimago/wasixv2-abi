//! [`Model`] -> syscall glue for Go's `wasix/wasm` port.
//!
//! Go's Linux code enters the kernel through `Syscall6(nr, a1, ..., a6)`. On `wasix/wasm` that is
//! `dispatch`: a switch from the riscv32 syscall number to the typed `wasixv2` import. Go's wasm
//! port is LP64 (8-byte `uintptr`, so a 64-bit param already fits one argument), while the
//! kernel reads wasm32's ILP32 layouts. A pointer param whose pointee lays out differently under
//! the two is handed to a hand-written `compat_<name>` converter when the syscall is in
//! [`COMPAT`], and otherwise fails with `ENOSYS` when non-NULL, so the kernel never misreads it.
//! `ret32`, `ret64`, `_ENOSYS` and the converters live in Go's `syscall_wasix_wasm.go`.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use anyhow::{Result, bail};

use crate::GeneratedFile;
use crate::ir::{
    Function, Layout, Model, Pointer, Record, Target, TyRef, TypeKind, ValType, names,
};

/// Paths relative to GOROOT.
pub const ZSYSCALL_PATH: &str = "src/internal/runtime/syscall/linux/zsyscall_wasix_wasm.go";
pub const ZSYSNUM_PATH: &str = "src/syscall/zsysnum_wasix_wasm.go";

const SYSCALL_MODULE: &str = crate::c::SYSCALL_MODULE;

/// Go's pointers, `long` and `size_t`.
const WORD: Layout = Layout { size: 8, align: 8 };

/// Syscalls whose structs Go converts by hand (`iovec`, and `msghdr` with its `cmsghdr` chain).
const COMPAT: &[&str] = &[
    "readv", "writev", "preadv", "pwritev", "preadv2", "pwritev2", "sendmsg", "recvmsg",
];

/// Pointees that, as arrays, are bitmasks: little-endian words of any width hold the same bytes.
const BITMASK_WORDS: &[&str] = &["ulong"];

/// `(WIT name, Go name)`: Go's names for calls riscv32 only has in a 64-bit-offset or 64-bit-time
/// form; emitted when the WIT name exists.
const SYS_ALIASES: &[(&str, &str)] = &[
    ("fcntl64", "FCNTL"),
    ("truncate64", "TRUNCATE"),
    ("ftruncate64", "FTRUNCATE"),
    ("sendfile64", "SENDFILE"),
    ("statfs64", "STATFS"),
    ("fstatfs64", "FSTATFS"),
    ("fadvise64-64", "FADVISE64"),
    ("utimensat-time64", "UTIMENSAT"),
    ("ppoll-time64", "PPOLL"),
    ("pselect6-time64", "PSELECT6"),
    ("timerfd-settime64", "TIMERFD_SETTIME"),
    ("timerfd-gettime64", "TIMERFD_GETTIME"),
    ("rt-sigtimedwait-time64", "RT_SIGTIMEDWAIT"),
    ("futex-time64", "FUTEX"),
    ("sched-rr-get-interval-time64", "SCHED_RR_GET_INTERVAL"),
    ("clock-gettime64", "CLOCK_GETTIME"),
    ("clock-settime64", "CLOCK_SETTIME"),
    ("clock-getres-time64", "CLOCK_GETRES"),
    ("clock-nanosleep-time64", "CLOCK_NANOSLEEP"),
    ("clock-adjtime64", "CLOCK_ADJTIME"),
    ("timer-settime64", "TIMER_SETTIME"),
    ("timer-gettime64", "TIMER_GETTIME"),
    ("recvmmsg-time64", "RECVMMSG"),
    ("semtimedop-time64", "SEMTIMEDOP"),
    ("mq-timedsend-time64", "MQ_TIMEDSEND"),
    ("mq-timedreceive-time64", "MQ_TIMEDRECEIVE"),
    ("io-pgetevents-time64", "IO_PGETEVENTS"),
];

/// asm-generic syscalls riscv32 leaves out (32-bit time, or replaced by a newer call). Go's
/// generic Linux code names them; `dispatch` has no case for them, so they fail with `ENOSYS`.
const MISSING: &[(&str, u32)] = &[
    ("FSTATAT", 79),
    ("FSTAT", 80),
    ("NANOSLEEP", 101),
    ("GETRLIMIT", 163),
    ("SETRLIMIT", 164),
    ("GETTIMEOFDAY", 169),
    ("SETTIMEOFDAY", 170),
    ("ADJTIMEX", 171),
    ("WAIT4", 260),
];

/// Generates the two Go files, in a fixed order.
pub fn generate(model: &Model) -> Result<Vec<GeneratedFile>> {
    if model.target != Target::WASM32 {
        bail!("the Go backend only supports wasm32, the kernel's side of Go's LP64 view");
    }
    let header = format!(
        "// Code generated by wasixv2-codegen from {}; DO NOT EDIT.\n\n//go:build wasix\n\n",
        model.package
    );
    let syscalls = functions(model, |f| f.nr.is_some());
    for name in COMPAT {
        if !syscalls.iter().any(|f| f.name == *name) {
            bail!("Go converts `{name}` by hand, but the definitions have no such syscall");
        }
    }
    let types = GoTypes { model };
    Ok(vec![
        GeneratedFile {
            path: ZSYSCALL_PATH,
            contents: zsyscall(&types, &header, &syscalls)?,
        },
        GeneratedFile {
            path: ZSYSNUM_PATH,
            contents: zsysnum(&header, &syscalls)?,
        },
    ])
}

/// The `wasixv2` functions that `keep` selects, by syscall number (extensions keep WIT order).
fn functions(model: &Model, keep: impl Fn(&Function) -> bool) -> Vec<&Function> {
    let mut out: Vec<&Function> = model
        .interfaces
        .iter()
        .filter(|i| i.module.as_deref() == Some(SYSCALL_MODULE))
        .flat_map(|i| &i.functions)
        .filter(|f| keep(f))
        .collect();
    out.sort_by_key(|f| f.nr);
    out
}

struct GoTypes<'a> {
    model: &'a Model,
}

impl GoTypes<'_> {
    /// The Go type of a param at the import boundary.
    fn scalar(&self, ty: &TyRef, origin: &str) -> Result<&'static str> {
        if self.pointer(ty).is_some() {
            return Ok("uintptr");
        }
        let Some(p) = self.model.scalar_prim(ty) else {
            bail!("{origin}: aggregates cannot cross the import boundary");
        };
        Ok(match (p.is_signed(), p.size()) {
            (true, 8) => "int64",
            (false, 8) => "uint64",
            (true, _) => "int32",
            (false, _) => "uint32",
        })
    }

    fn pointer(&self, ty: &TyRef) -> Option<&Pointer> {
        let TyRef::Named(n) = ty else { return None };
        match &self.model.type_def(n)?.kind {
            TypeKind::Pointer(p) => Some(p),
            _ => None,
        }
    }

    /// The pointee of `ty` when Go lays it out differently from the kernel.
    fn lp64_sensitive(&self, ty: &TyRef) -> Option<String> {
        let ptr = self.pointer(ty)?;
        let pointee = ptr.pointee.as_ref()?;
        let elem = if ptr.array {
            TyRef::Array(Box::new(pointee.clone()), 1)
        } else {
            pointee.clone()
        };
        let (_, same) = self.go_layout(&elem);
        (!same).then(|| crate::rust::wit_ty(pointee))
    }

    /// Go's layout of `ty`, and whether it matches the kernel's (offsets included).
    ///
    /// Go is LP64: pointers, `long` and `size_t` take 8 bytes. Arrays of [`BITMASK_WORDS`] keep
    /// their bytes, as do unions of the kernel's size: the kernel stores them without reading a
    /// member (`epoll_data`).
    fn go_layout(&self, ty: &TyRef) -> (Layout, bool) {
        let kernel = self.model.layout(ty);
        match ty {
            TyRef::Prim(_) => (kernel, true),
            TyRef::Array(elem, _) if self.is_bitmask_word(elem) => (kernel, true),
            TyRef::Array(elem, n) => {
                let (l, same) = self.go_layout(elem);
                let size = l.size * n;
                (Layout { size, ..l }, same)
            }
            TyRef::Named(name) => {
                let def = self.model.type_def(name).expect("validated model");
                match &def.kind {
                    TypeKind::Alias(a) if a.pointer_sized => (WORD, false),
                    TypeKind::Alias(a) => self.go_layout(&a.target),
                    TypeKind::Pointer(_) => (WORD, false),
                    TypeKind::Constants(_) => (kernel, true),
                    TypeKind::Record(r) => self.record_layout(r, kernel),
                }
            }
        }
    }

    fn record_layout(&self, r: &Record, kernel: Layout) -> (Layout, bool) {
        let (mut end, mut align, mut same) = (0u32, 1u32, true);
        for f in &r.fields {
            let (l, field_same) = self.go_layout(&f.ty);
            let offset = if r.is_union {
                0
            } else {
                end.next_multiple_of(l.align)
            };
            same &= r.is_union || (field_same && offset == f.offset);
            end = end.max(offset + l.size);
            align = align.max(l.align);
        }
        let layout = Layout {
            size: end.next_multiple_of(align),
            align,
        };
        (layout, same && layout == kernel)
    }

    fn is_bitmask_word(&self, ty: &TyRef) -> bool {
        matches!(ty, TyRef::Named(n) if BITMASK_WORDS.contains(&n.as_str()))
    }

    fn result(&self, f: &Function) -> Result<Option<(&'static str, &'static str)>> {
        let Some(r) = &f.result else { return Ok(None) };
        let origin = format!("result of `{}`", f.name);
        match self.model.valtype(r) {
            Some(ValType::I64) => Ok(Some(("int64", "ret64"))),
            Some(ValType::I32) => Ok(Some(("int32", "ret32"))),
            None => bail!("{origin}: aggregates cannot cross the import boundary"),
        }
    }
}

fn param_ident(kebab: &str) -> String {
    names::snake(kebab) + "_"
}

fn declaration(t: &GoTypes<'_>, go_name: &str, f: &Function) -> Result<String> {
    let mut params = Vec::new();
    for p in &f.params {
        let origin = format!("param `{}` of `{}`", p.name, f.name);
        params.push(format!(
            "{} {}",
            param_ident(&p.name),
            t.scalar(&p.ty, &origin)?
        ));
    }
    let result = t
        .result(f)?
        .map_or(String::new(), |(ty, _)| format!(" {ty}"));
    Ok(format!(
        "//go:wasmimport {SYSCALL_MODULE} {}\nfunc {go_name}({}){result}\n",
        f.import_name,
        params.join(", ")
    ))
}

fn import_fn(f: &Function) -> String {
    format!("wasixv2_{}", names::snake(&f.name))
}

fn case(t: &GoTypes<'_>, f: &Function) -> Result<String> {
    let nr = f.nr.expect("syscalls have numbers");
    let mut out = format!("\tcase {nr}: // {}\n", f.import_name);
    if f.params.len() > 6 {
        bail!(
            "syscall `{}` takes more than Syscall6's six arguments",
            f.name
        );
    }
    let regs: Vec<String> = (1..=f.params.len()).map(|i| format!("a{i}")).collect();
    if COMPAT.contains(&f.name.as_str()) {
        let _ = writeln!(
            out,
            "\t\treturn compat_{}({})",
            names::snake(&f.name),
            regs.join(", ")
        );
        return Ok(out);
    }
    let mut args = Vec::new();
    for (p, reg) in f.params.iter().zip(&regs) {
        let origin = format!("param `{}` of `{}`", p.name, f.name);
        let ty = t.scalar(&p.ty, &origin)?;
        if let Some(pointee) = t.lp64_sensitive(&p.ty) {
            let _ = write!(
                out,
                "\t\tif {reg} != 0 {{\n\t\t\treturn 0, _ENOSYS // {}: {pointee} differs from Go's \
                 LP64 layout\n\t\t}}\n",
                names::snake(&p.name)
            );
        }
        args.push(if ty == "uintptr" {
            reg.clone()
        } else {
            format!("{ty}({reg})")
        });
    }
    let call = format!("{}({})", import_fn(f), args.join(", "));
    match t.result(f)? {
        Some((_, ret)) => {
            let _ = writeln!(out, "\t\treturn {ret}({call})");
        }
        None => {
            let _ = writeln!(out, "\t\t{call}\n\t\treturn 0, 0");
        }
    }
    Ok(out)
}

fn zsyscall(t: &GoTypes<'_>, header: &str, syscalls: &[&Function]) -> Result<String> {
    let mut out =
        format!("{header}package linux\n\n// Syscall imports: one per riscv32 syscall.\n");
    for f in syscalls {
        out.push('\n');
        out.push_str(&declaration(t, &import_fn(f), f)?);
    }
    out.push_str("\n// Extensions: wasm-specific primitives.\n");
    for f in functions(t.model, |f| f.nr.is_none()) {
        out.push('\n');
        out.push_str(&declaration(
            t,
            &format!("Ext{}", names::upper_camel(&f.name)),
            f,
        )?);
    }
    out.push_str(
        "\n// dispatch calls the import for riscv32 syscall number num.\n//\n//go:nosplit\n\
         func dispatch(num, a1, a2, a3, a4, a5, a6 uintptr) (r1, errno uintptr) {\n\tswitch num {\n",
    );
    for f in syscalls {
        out.push_str(&case(t, f)?);
    }
    out.push_str("\t}\n\treturn 0, _ENOSYS\n}\n");
    Ok(out)
}

fn zsysnum(header: &str, syscalls: &[&Function]) -> Result<String> {
    let sys = |name: &str| format!("SYS_{name}");
    let numbers: BTreeMap<String, u32> = syscalls
        .iter()
        .map(|f| {
            (
                names::screaming(&f.name),
                f.nr.expect("syscalls have numbers"),
            )
        })
        .collect();
    let mut blocks = vec![(
        None,
        syscalls
            .iter()
            .map(|f| (sys(&names::screaming(&f.name)), f.nr.unwrap().to_string()))
            .collect::<Vec<_>>(),
    )];

    let aliases = SYS_ALIASES
        .iter()
        .map(|(wit, go)| (*go, names::screaming(wit)))
        .filter(|(go, target)| numbers.contains_key(target) && !numbers.contains_key(*go))
        .map(|(go, target)| (sys(go), sys(&target)))
        .collect();
    blocks.push((
        Some("Go's names for calls riscv32 only has in a 64-bit-offset or 64-bit-time form."),
        aliases,
    ));

    let mut missing = Vec::new();
    for (go, nr) in MISSING {
        if let Some((name, _)) = numbers.iter().find(|(_, n)| *n == nr) {
            bail!("`SYS_{go}` ({nr}) is listed as missing, but `{name}` has that number");
        }
        missing.push((sys(go), nr.to_string()));
    }
    blocks.push((
        Some("asm-generic calls riscv32 leaves out: dispatch fails them with ENOSYS."),
        missing,
    ));

    let mut out = format!("{header}package syscall\n\nconst (\n");
    for (i, (comment, lines)) in blocks.iter().enumerate() {
        if i > 0 {
            out.push('\n');
        }
        if let Some(c) = comment {
            let _ = writeln!(out, "\t// {c}");
        }
        // gofmt aligns the `=` of consecutive specs.
        let width = lines.iter().map(|(n, _)| n.len()).max().unwrap_or(0);
        for (name, value) in lines {
            let _ = writeln!(out, "\t{name:width$} = {value}");
        }
    }
    out.push_str(")\n");
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::parse::parse_str;

    const TYPES: &str = "package t:t@0.1.0;\ninterface types {\n\
        /// @pointer-sized\ntype uptr = u32;\n/// @pointer-sized\ntype slong = s32;\n\
        /// @pointer-sized\ntype ulong = u32;\n\
        /// @ptr(mut void)\ntype vp = uptr;\n\
        record iovec { base: uptr, len: ulong }\n/// @ptr(const iovec[])\ntype iovp = uptr;\n\
        record ts { sec: s64, nsec: s64 }\n/// @ptr(mut ts)\ntype tsp = uptr;\n\
        /// @ptr(mut ulong[])\ntype mask = uptr;\n";

    const USES: &str = "use types.{uptr, slong, ulong, vp, iovp, tsp, mask};";

    fn model(funcs: &str) -> Model {
        let src = format!(
            "{TYPES}\n}}\n/// @module(wasixv2)\ninterface syscalls {{\n{USES}\n{funcs}\n}}\n\
             /// @module(wasixv2)\ninterface ext {{\n{USES}\nstartup-size: func() -> u32;\n}}\n"
        );
        parse_str("t.wit", &src, Target::WASM32).unwrap()
    }

    const COMPAT_DEFS: &str = "\
        /// @nr(65)\nreadv: func(fd: s32, v: iovp, n: ulong) -> slong;\n\
        /// @nr(66)\nwritev: func(fd: s32, v: iovp, n: ulong) -> slong;\n\
        /// @nr(69)\npreadv: func(fd: s32, v: iovp, n: ulong, pos: s64) -> slong;\n\
        /// @nr(70)\npwritev: func(fd: s32, v: iovp, n: ulong, pos: s64) -> slong;\n\
        /// @nr(286)\npreadv2: func(fd: s32, v: iovp, n: ulong, pos: s64, f: u32) -> slong;\n\
        /// @nr(287)\npwritev2: func(fd: s32, v: iovp, n: ulong, pos: s64, f: u32) -> slong;\n\
        /// @nr(211)\nsendmsg: func(fd: s32, m: vp, f: u32) -> slong;\n\
        /// @nr(212)\nrecvmsg: func(fd: s32, m: vp, f: u32) -> slong;\n\
        /// @nr(25)\nfcntl64: func(fd: s32, cmd: s32, arg: ulong) -> slong;\n";

    fn generated(funcs: &str) -> Result<Vec<GeneratedFile>> {
        generate(&model(&format!("{COMPAT_DEFS}{funcs}")))
    }

    fn file(funcs: &str, path: &str) -> String {
        generated(funcs)
            .unwrap()
            .into_iter()
            .find(|f| f.path == path)
            .unwrap()
            .contents
    }

    #[test]
    fn imports_and_dispatch() {
        let z = file(
            "/// @nr(62)\nlseek: func(fd: s32, off: s64, whence: u32) -> s64;\n\
             /// @nr(94)\nexit-group: func(code: s32);\n\
             /// @nr(1)\nnap: func(t: tsp, m: mask, v: iovp) -> slong;",
            ZSYSCALL_PATH,
        );
        assert!(
            z.starts_with("// Code generated by wasixv2-codegen from t:t@0.1.0; DO NOT EDIT.\n\n//go:build wasix\n\npackage linux\n"),
            "{z}"
        );
        assert!(z.contains("//go:wasmimport wasixv2 lseek\nfunc wasixv2_lseek(fd_ int32, off_ int64, whence_ uint32) int64\n"), "{z}");
        assert!(z.contains("\tcase 62: // lseek\n\t\treturn ret64(wasixv2_lseek(int32(a1), int64(a2), uint32(a3)))\n"), "{z}");
        assert!(
            z.contains(
                "\tcase 94: // exit_group\n\t\twasixv2_exit_group(int32(a1))\n\t\treturn 0, 0\n"
            ),
            "{z}"
        );
        assert!(
            z.contains("\tcase 66: // writev\n\t\treturn compat_writev(a1, a2, a3)\n"),
            "{z}"
        );
        assert!(
            z.contains("//go:wasmimport wasixv2 startup_size\nfunc ExtStartupSize() int32\n"),
            "{z}"
        );
        // Fixed-width structs and bitmasks pass through; pointer-holding structs are refused.
        assert!(
            z.contains("\tcase 1: // nap\n\t\tif a3 != 0 {\n\t\t\treturn 0, _ENOSYS // v: iovec differs from Go's LP64 layout\n\t\t}\n\t\treturn ret32(wasixv2_nap(a1, a2, a3))\n"),
            "{z}"
        );
    }

    #[test]
    fn numbers_aliases_and_missing() {
        let n = file("", ZSYSNUM_PATH);
        assert!(n.contains("\tSYS_FCNTL64  = 25\n"), "{n}");
        assert!(n.contains("\tSYS_PWRITEV2 = 287\n"), "{n}");
        assert!(n.contains("\t// Go's names for calls riscv32 only has in a 64-bit-offset or 64-bit-time form.\n\tSYS_FCNTL = SYS_FCNTL64\n"), "{n}");
        assert!(n.contains("\tSYS_FSTATAT      = 79\n"), "{n}");
    }

    #[test]
    fn errors() {
        let e = |funcs: &str| format!("{:#}", generated(funcs).err().unwrap());
        assert!(e("/// @nr(80)\nfstat: func() -> slong;").contains("listed as missing"));
        assert!(format!("{:#}", generate(&model("")).err().unwrap()).contains("converts `readv`"));
    }
}
